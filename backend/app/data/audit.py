"""Reports which numbers of the model are placeholders or have no source.

    python -m app.data.audit                      # print to stdout
    python -m app.data.audit --output ../docs/assumptions.md

Every `placeholder: true` value is a stand-in to be replaced or confirmed; every value
without a `source` is an unsourced assumption (CLAUDE.md sections 17 and 40).
"""

import argparse
from pathlib import Path

from app.data.loader import Catalog, iter_catalog_values, load_catalog


def _cell(text: str | None) -> str:
    return (text or "").replace("\n", " ").replace("|", "/")


def _row(owner: str, path: str, notes: str | None, value: float) -> str:
    where = f"{owner} `{path}`" if path else owner
    return f"| {where} | {value:g} | {_cell(notes)} |"


def build_report(catalog: Catalog) -> str:
    placeholders: list[str] = []
    unsourced: list[str] = []
    total = 0
    for owner, path, value in iter_catalog_values(catalog):
        total += 1
        if value.placeholder:
            placeholders.append(_row(owner, path, value.notes, value.value))
        elif value.source is None:
            unsourced.append(_row(owner, path, value.notes, value.value))

    band_rows = [
        f"| questionnaire:{name} | {len(group.bands)} bands | {_cell(group.notes)} |"
        for name, group in catalog.questionnaire.groups.items()
        if group.placeholder
    ]
    band_rows += [
        f"| mission template:{purpose} | categorical | {_cell(template.notes)} |"
        for purpose, template in catalog.mission_templates.items()
        if template.placeholder
    ]
    rules = catalog.portfolio_rules
    if rules.placeholder:
        band_rows.append(
            f"| portfolio rules | {len(rules.addon_sets)} add-on sets, "
            f"{len(rules.service_layer)} services | Which candidate portfolios are generated "
            "(data/portfolio_rules.yaml): a modelling choice to review. |"
        )

    if catalog.feasibility_rules.placeholder:
        band_rows.append(
            "| feasibility rules | categorical | Which means are for the occasional trip only, "
            "who cannot carry children, accessibility exclusions "
            "(data/feasibility_rules.yaml): modelling choices to review. |"
        )

    if catalog.assignment_rules.placeholder:
        band_rows.append(
            "| assignment rules | categorical | Hours spent at the destination for each kind of "
            "mission, weight of the weather on each mission "
            "(data/assignment_rules.yaml): modelling choices to review. |"
        )

    header = "| Value | Number | Notes |\n|---|---:|---|"
    lines = [
        "# Assumptions audit",
        "",
        "Generated by `python -m app.data.audit` - do not edit by hand.",
        "",
        f"Data snapshot `{catalog.version}`. {total} numbers in total: "
        f"{len(placeholders)} placeholders, {len(unsourced)} unsourced (not placeholders), "
        f"{total - len(placeholders) - len(unsourced)} sourced.",
        "",
        "## Placeholders (to be replaced or confirmed)",
        "",
        header,
        *placeholders,
        "",
        "## Questionnaire bands and mission templates (placeholders)",
        "",
        "| Group | Size | Notes |",
        "|---|---:|---|",
        *band_rows,
        "",
        "## Unsourced assumptions (reasoned estimates, no source)",
        "",
        header,
        *unsourced,
        "",
    ]
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, help="write the report to this file (UTF-8)")
    args = parser.parse_args()
    report = build_report(load_catalog())
    if args.output:
        args.output.write_text(report, encoding="utf-8")
    else:
        print(report)


if __name__ == "__main__":
    main()
